/**
 * Write an enemies/<slug>.txt from a Studio enemy map object.
 * The enemy editor used to only store loot and stats on the map JSON;
 * Flare needs the definition file.
 */
import type { MapObject } from '@/types';
import { applyEnemyFileUpdates } from '@/adapters/flare/flareAdapter.cjs';
import { writeProjectFiles, projectRoot } from '@/editor/projectFiles';
import { SPAWN_CONDITION_KEYS } from '@/editor/enemySpawnConditions';
import { propertyRecord, propertyText } from '@/editor/propertyText';
import { enemyFilePath } from '@/utils/enemyFileHydrate';

const STUDIO_ONLY_KEYS = new Set([
  'enemyFilename', 'sourcePath', 'tilesetPath', 'portraitPath',
  'tilesetSourcePath', 'portraitSourcePath', 'templateImage',
  'include', 'abilities', 'renderLayers', 'animationSlots',
  'melee', 'ranged', 'caster', 'summoner', 'boss', 'passive', 'stationary',
]);

const LIST_KEYS = new Set(['loot', 'stat', 'stat_per_level', 'stat_per_primary']);
const MAP_ONLY_KEYS = new Set<string>(SPAWN_CONDITION_KEYS);

/** Project-relative enemies/...txt path, same rule as the editor save. */
export function enemyRelPath(object: Pick<MapObject, 'name' | 'properties'>): string {
  return enemyFilePath('', object).replace(/\\/g, '/').replace(/^\//, '');
}

export function enemyFileTextFromObject(object: Pick<MapObject, 'name' | 'level' | 'category' | 'properties'>, existingText = ''): { text: string; warnings: string[] } {
  const props = propertyRecord(object.properties as Record<string, string | string[]> | undefined);
  const includes = propertyText(props.include).split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  const fields: Record<string, string> = {};
  if (object.name) fields.name = object.name;
  const categories = object.category || props.categories || props.category;
  if (categories) fields.categories = categories;
  if (object.level != null && Number.isFinite(Number(object.level))) fields.level = String(object.level);

  const listFields: Record<string, string[]> = {};
  for (const key of LIST_KEYS) {
    const raw = propertyText(props[key]);
    if (!raw) continue;
    listFields[key] = raw.split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  }

  for (const [key, value] of Object.entries(props)) {
    if (!value || STUDIO_ONLY_KEYS.has(key) || LIST_KEYS.has(key) || MAP_ONLY_KEYS.has(key) || key === 'categories' || key === 'category' || key === 'name' || key === 'level') continue;
    if (key === 'powers') {
      // Studio sometimes stores a JSON array; Flare wants power=state,id,chance lines.
      const trimmed = value.trim();
      if (trimmed.startsWith('[')) {
        try {
          const parsed = JSON.parse(trimmed) as Array<{ id?: string; state?: string; chance?: string | number }>;
          const lines = parsed
            .filter((entry) => entry?.id)
            .map((entry) => `${entry.state || 'melee'},${entry.id},${entry.chance ?? 100}`);
          if (lines.length) listFields.power = lines;
        } catch {
          /* leave unparsed JSON out of the file */
        }
        continue;
      }
    }
    fields[key] = value;
  }

  return applyEnemyFileUpdates(existingText, {
    header: existingText.trim() ? undefined : '# Enemy file generated by Flare Studio',
    includes,
    fields,
    listFields,
  });
}

export async function writeEnemyDefinition(projectPath: string, object: MapObject): Promise<boolean> {
  if (!projectPath) return false;
  const rel = enemyRelPath(object);
  const root = projectRoot(projectPath);
  let existing = '';
  try {
    existing = (await window.electronAPI?.readFile?.(`${root}/${rel}`)) || '';
  } catch {
    existing = '';
  }
  const { text } = enemyFileTextFromObject(object, existing);
  return writeProjectFiles(projectPath, [{ path: rel, content: text }]);
}
